#!/usr/bin/env bash
# secrets.env (generated once, never overwritten), .env (the values docker-compose.yml reads, rewritten on
# every run) and generated/hub-apps.env (the Hub's per-app switches).
#
# Secrets are generated once and only ever added: rotating an encryption key in place makes the data stored
# with it unreadable. A re-run only adds keys that are missing. Every secret is generated up front (also for
# apps that are not installed), so docker compose never meets an empty variable.

SECRETS_FILE="$ROOT/secrets.env"
ENV_FILE="$ROOT/.env"
HUB_APPS_FILE="$ROOT/generated/hub-apps.env"

# KEY spec  (spec: @alnum:N | @hex:N bytes | @b64:N bytes | @pksign | a literal value)
SECRET_SPECS="
OL_DB_PASSWORD @alnum:24
KEYCLOAK_ADMIN_USER admin
KEYCLOAK_ADMIN_PASSWORD @alnum:24
OL_HUB_ENCRYPT_SECRET @alnum:32
OL_HUB_PK_API_KEY_SIGN @pksign
OL_INTERNAL_SERVICE_SECRET @hex:32
KEYCLOAK_MANAGEMENT_CLIENT_SECRET @alnum:32
HUB_ADMIN_PASSWORD @alnum:20
OL_CODE_ADMIN admin
OL_CODE_PASSWORD @alnum:24
OL_CODE_CREDENTIAL_ENCRYPTION_KEY @hex:32
OL_TERMINAL_ADMIN admin
OL_TERMINAL_PASSWORD @alnum:24
OL_TERMINAL_CREDENTIAL_ENCRYPTION_KEY @hex:32
COREIQ_ADMIN admin
COREIQ_PASSWORD @alnum:24
COREIQ_ADMIN_PASSKEY @alnum:32
COREIQ_CREDENTIAL_ENCRYPTION_KEY @hex:32
ATOMIQ_ADMIN_PASSKEY @alnum:32
ATOMIQ_SETTINGS_ENCRYPTION_KEY @hex:32
ATOMIQ_CREDENTIAL_ENCRYPTION_KEY @hex:32
DATAIQ_DB_ENCRYPTION_SECRET @b64:32
DATAIQ_BATCH_API_KEY @hex:24
"

IMAGE_KEYS="IMAGE_POSTGRES IMAGE_KEYCLOAK IMAGE_HUB IMAGE_PROXY IMAGE_OL_INTEGRATION IMAGE_OL_TERMIQ IMAGE_OL_DATAIQ
IMAGE_OL_DATAIQ_BATCH IMAGE_OL_APPIQ IMAGE_OL_NEXT IMAGE_OL_SPEC IMAGE_OL_CODE IMAGE_OL_TERMINAL IMAGE_OL_COREIQ IMAGE_OL_ATOMIQ"

# ---- generators (only /dev/urandom and coreutils; openssl for the RSA key, or the PostgreSQL image's) ------
gen_alnum() {
  local out=""
  while [ ${#out} -lt "$1" ]; do out="$out$(head -c 600 /dev/urandom | LC_ALL=C tr -dc 'A-Za-z0-9')"; done
  printf '%s' "${out:0:$1}"
}
gen_hex() { head -c "$1" /dev/urandom | od -An -tx1 -v | tr -d ' \n'; }
gen_b64() { head -c "$1" /dev/urandom | base64 | tr -d '\n'; }
# Hub API-key signing key, in the format the Hub reads: "{base64}" + base64(PKCS#8 PEM, RSA 2048)
gen_pk_sign() {
  local pem=""
  if command -v openssl >/dev/null 2>&1; then
    pem=$(openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 2>/dev/null | tr -d '\r' || true)
  fi
  if [ -z "$pem" ]; then
    info "openssl not found here - generating the Hub signing key with the PostgreSQL image"
    pem=$(docker run --rm --entrypoint openssl "$IMAGE_POSTGRES" genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 2>/dev/null | tr -d '\r' || true)
  fi
  case $pem in *"BEGIN PRIVATE KEY"*) ;; *) die "Could not generate an RSA key (install openssl and re-run)" ;; esac
  printf '{base64}%s' "$(printf '%s\n' "$pem" | base64 | tr -d '\n')"
}

ensure_secrets() {
  local added=0 key spec val
  if [ ! -f "$SECRETS_FILE" ]; then
    cat > "$SECRETS_FILE" <<'EOF'
# OpenLegacy Hub - secrets. Generated once by ol-hub-docker.sh; values are only ever added, never changed.
# KEEP THIS FILE and back it up together with the data volumes: the encryption keys below are needed to read
# the data. To change a password, change it here AND in the component (Keycloak console, ...), then re-run.
EOF
  fi
  chmod 600 "$SECRETS_FILE" 2>/dev/null || true
  while read -r key spec; do
    [ -n "$key" ] || continue
    grep -q "^$key=" "$SECRETS_FILE" && continue
    case $spec in
      @alnum:*) val=$(gen_alnum "${spec#@alnum:}") ;;
      @hex:*)   val=$(gen_hex "${spec#@hex:}") ;;
      @b64:*)   val=$(gen_b64 "${spec#@b64:}") ;;
      @pksign)  val=$(gen_pk_sign) ;;
      *)        val=$spec ;;
    esac
    [ -n "$val" ] || die "could not generate $key"
    printf "%s='%s'\n" "$key" "$val" >> "$SECRETS_FILE"
    added=$((added + 1))
  done <<EOF
$SECRET_SPECS
EOF
  load_kv_file "$SECRETS_FILE"
  if [ "$added" -gt 0 ]; then ok "secrets.env: $added value(s) generated"; else info "secrets.env exists - unchanged"; fi
}

secret() { tr -d '\r' < "$SECRETS_FILE" 2>/dev/null | sed -n "s/^$1='\(.*\)'\$/\1/p"; }

# The compose profiles for the selected apps (+ the bundled database)
compose_profiles() {
  local p="" a
  [ "$BUNDLED_DB" = true ] && p="bundled-db"
  for a in $SELECTED_APPS; do p="${p:+$p,}$a"; done
  printf '%s' "$p"
}

# .env: everything docker-compose.yml reads. Rewritten on every run; edit install.conf / images.conf instead.
write_env() {
  local tmp="$ENV_FILE.tmp.$$" k
  kv() { printf "%s='%s'\n" "$1" "$2"; }
  {
    echo "# GENERATED by ol-hub-docker.sh from install.conf, images.conf and secrets.env on $(date '+%Y-%m-%d %H:%M')."
    echo "# Do not edit: change those files and run ./ol-hub-docker.sh again."
    kv COMPOSE_PROFILES "$(compose_profiles)"
    if is_localhost_domain; then
      # *.localhost names need hosts-file entries in the app containers (see docker-compose.localhost.yml)
      kv COMPOSE_PATH_SEPARATOR ":"
      kv COMPOSE_FILE "docker-compose.yml:docker-compose.localhost.yml"
    fi
    echo "# addresses"
    kv HUB_HOST "$HUB_HOST"; kv KEYCLOAK_HOST "$KEYCLOAK_HOST"; kv OL_CODE_HOST "$OL_CODE_HOST"
    kv OL_TERMINAL_HOST "$OL_TERMINAL_HOST"; kv OL_DATAIQ_BATCH_HOST "$OL_DATAIQ_BATCH_HOST"
    kv PUBLIC_HUB_URL "$PUBLIC_HUB_URL"; kv PUBLIC_KEYCLOAK_URL "$PUBLIC_KEYCLOAK_URL"
    kv PUBLIC_OL_CODE_URL "$PUBLIC_OL_CODE_URL"; kv PUBLIC_OL_TERMINAL_URL "$PUBLIC_OL_TERMINAL_URL"
    kv PUBLIC_OL_DATAIQ_BATCH_URL "$PUBLIC_OL_DATAIQ_BATCH_URL"
    kv APP_REDIRECT_URLS "$APP_REDIRECT_URLS"; kv APP_HOST_LABEL "$APP_HOST_LABEL"
    kv HTTPS_PORT "$HTTPS_PORT"; kv HTTP_PORT "$HTTP_PORT"; kv TLS_MODE "$TLS_MODE"; kv ACME_EMAIL "$ACME_EMAIL"
    echo "# database"
    if [ "$BUNDLED_DB" = true ]; then
      kv OL_DB_HOST hub-enterprise-postgres; kv OL_DB_PORT 5432
    else
      kv OL_DB_HOST "$DB_HOST"; kv OL_DB_PORT "$DB_PORT"
    fi
    kv OL_DB_NAME "$DB_NAME"; kv OL_DB_USER "$DB_USER"
    if [ "$BUNDLED_DB" = true ]; then kv OL_DB_PASSWORD "$(secret OL_DB_PASSWORD)"; else kv OL_DB_PASSWORD "$DB_PASSWORD"; fi
    echo "# images"
    for k in $IMAGE_KEYS; do
      eval "[ -n \"\${$k:-}\" ]" || die "$k is not set (images.conf)"
      eval "kv $k \"\${$k}\""
    done
    echo "# secrets (from secrets.env)"
    while read -r k _; do
      if [ -n "$k" ] && [ "$k" != OL_DB_PASSWORD ]; then kv "$k" "$(secret "$k")"; fi
    done <<EOF
$SECRET_SPECS
EOF
  } > "$tmp"
  mv "$tmp" "$ENV_FILE"
  chmod 600 "$ENV_FILE" 2>/dev/null || true
  # values that only exist in .env (OL_DB_HOST, ...) for the rest of this run
  load_kv_file "$ENV_FILE"
}

# generated/hub-apps.env: the Hub settings of the apps switched on (config/hub/apps/<app>.env).
# An app is switched on only once it answers: a switch without a running app stops the Hub shell from loading.
write_hub_switches() {   # write_hub_switches "app app ..."
  mkdir -p "$ROOT/generated"
  local tmp="$HUB_APPS_FILE.tmp.$$" a
  {
    echo "# GENERATED by ol-hub-docker.sh: RBAC source + the Hub settings of every app switched on in the Hub."
    echo "# Switched on: ${1:-<none>}"
    in_list ol-integration $1 || tr -d '\r' < "$ROOT/config/hub/rbac-hub.env"
    for a in $1; do
      tr -d '\r' < "$ROOT/config/hub/apps/$a.env" | sed \
        -e "s|\${PUBLIC_HUB_URL}|$PUBLIC_HUB_URL|g" \
        -e "s|\${PUBLIC_KEYCLOAK_URL}|$PUBLIC_KEYCLOAK_URL|g" \
        -e "s|\${PUBLIC_OL_CODE_URL}|$PUBLIC_OL_CODE_URL|g" \
        -e "s|\${PUBLIC_OL_TERMINAL_URL}|$PUBLIC_OL_TERMINAL_URL|g" \
        -e "s|\${PUBLIC_OL_DATAIQ_BATCH_URL}|$PUBLIC_OL_DATAIQ_BATCH_URL|g"
    done
  } > "$tmp"
  mv "$tmp" "$HUB_APPS_FILE"
}

# Apps switched on in the Hub right now (from generated/hub-apps.env)
hub_switched_on() {
  [ -f "$HUB_APPS_FILE" ] && sed -n 's/^# Switched on: //p' "$HUB_APPS_FILE" | sed 's/<none>//'
  return 0
}
